import assert from 'node:assert/strict';
import { once } from 'node:events';
import { join } from 'node:path';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
import { createDevServer } from '../scripts/serve.mjs';
import { root } from '../scripts/files.mjs';

const server = createDevServer(); server.listen(0, '127.0.0.1'); await once(server, 'listening');
let browser;
try {
    browser = await chromium.launch({headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? {channel: process.env.PLAYWRIGHT_CHANNEL} : {}), args: ['--autoplay-policy=no-user-gesture-required']});
    const page = await browser.newPage({viewport: {width: 1280, height: 800}});
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
    const base = `http://127.0.0.1:${server.address().port}`;
    await page.goto(base);
    assert.equal(await page.title(), 'Milkdrop-Player');
    assert.equal(await page.locator('.app-name').innerText(), 'Milkdrop-Player');
    assert.equal(await page.locator('#track-title').innerText(), '尚未选择媒体');
    assert.equal(await page.locator('.playlist-count').innerText(), '0');
    const rate = 8000, samples = rate * 30, wav = Buffer.alloc(44 + samples * 2);
    wav.write('RIFF'); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8);
    wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
    wav.writeUInt32LE(rate, 24); wav.writeUInt32LE(rate * 2, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write('data', 36); wav.writeUInt32LE(samples * 2, 40);
    for (let i = 0; i < samples; i++) wav.writeInt16LE(Math.sin(2 * Math.PI * 220 * i / rate) * 4000, 44 + i * 2);
    const title = 'Generated tone — long filename for layout verification.wav';
    await page.locator('#f').setInputFiles({name: title, mimeType: 'audio/wav', buffer: wav});
    await page.waitForFunction(() => document.querySelector('wm-player').currentTime > .2);
    assert.equal(await page.locator('#track-title').innerText(), title);
    assert.equal(await page.locator('.playlist-count').innerText(), '1');
    assert.equal(await page.locator('#duration').innerText(), '00:30');
    assert.equal(await page.locator('#track-state').innerText(), '正在播放');
    const seek = await page.locator('.seek').boundingBox();
    assert.ok(seek.width > 100 && seek.height > 0, 'Seek control must have a clickable area');
    await page.locator('.seek').click({position: {x: seek.width / 2, y: seek.height / 2}});
    await page.waitForFunction(() => document.querySelector('wm-player').currentTime > 10);
    await page.locator('.play-pause').click();
    assert.equal(await page.locator('#track-state').innerText(), '已暂停');
    await page.locator('.play-pause').click();
    await page.locator('#immersive-toggle').click();
    assert.equal(await page.locator('#immersive-toggle').getAttribute('aria-pressed'), 'true');
    await page.waitForFunction(() => document.querySelector('wm-player').shadowRoot.getElementById('canvas').height === innerHeight);
    assert.equal(await page.locator('#playlist-toggle').getAttribute('aria-expanded'), 'false');
    await page.mouse.move(600, 350);
    await page.waitForFunction(() => document.querySelector('wm-player').classList.contains('is-idle'), null, {timeout: 6000});
    await page.waitForFunction(() => getComputedStyle(document.querySelector('wm-player').shadowRoot.getElementById('top-actions')).opacity === '0');
    if (process.argv.includes('--screenshots')) {
        await mkdir(join(root, 'docs/images'), {recursive: true});
        await page.screenshot({path: join(root, 'docs/images/immersive.png')});
    }
    await page.keyboard.press('Tab');
    await page.waitForFunction(() => !document.querySelector('wm-player').classList.contains('is-idle'));
    await page.waitForTimeout(3700);
    assert.equal(await page.evaluate(() => document.querySelector('wm-player').classList.contains('is-idle')), false);
    await page.locator('#immersive-toggle').click();
    assert.equal(await page.locator('#playlist-toggle').getAttribute('aria-expanded'), 'true');
    await page.locator('.playlist-close').click();
    assert.equal(await page.locator('#playlist-toggle').getAttribute('aria-expanded'), 'false');
    await page.locator('#playlist-toggle').click();
    await page.setViewportSize({width: 390, height: 844});
    await page.waitForFunction(() => !document.querySelector('wm-player').classList.contains('show-playlist'));
    await page.locator('#playlist-toggle').click();
    assert.ok(await page.locator('.playlist-container').isVisible());
    if (process.argv.includes('--screenshots')) await page.screenshot({path: join(root, 'docs/images/mobile-drawer.png')});
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#playlist-toggle').getAttribute('aria-expanded'), 'false');
    await page.locator('#playlist-toggle').click();
    await page.locator('#drawer-backdrop').click({position: {x: 5, y: 20}});
    assert.equal(await page.locator('#playlist-toggle').getAttribute('aria-expanded'), 'false');
    const mobile = await browser.newPage({viewport: {width: 320, height: 640}, isMobile: true, hasTouch: true});
    await mobile.goto(base);
    assert.equal(await mobile.locator('#playlist-toggle').getAttribute('aria-expanded'), 'false');
    await mobile.locator('#playlist-toggle').tap();
    assert.ok(await mobile.locator('.playlist-container').isVisible());
    await mobile.locator('.playlist-close').tap();
    assert.equal(await mobile.locator('#playlist-toggle').getAttribute('aria-expanded'), 'false');
    assert.deepEqual(errors, []);
    console.log('PASS: app name, real metadata/count/state, immersive canvas, idle hiding, keyboard recovery, playlist restoration, mobile drawer/Escape/backdrop/touch');
} finally {
    if (browser) await browser.close();
    await new Promise(resolve => server.close(resolve));
}
